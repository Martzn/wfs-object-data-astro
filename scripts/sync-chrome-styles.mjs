import { mkdir, readFile, writeFile } from 'node:fs/promises';

const origin = 'https://firmen.standort-sachsen.de';
const root = new URL('../public/brand/original/', import.meta.url);
const stylesheetNames = ['font.css', 'wfs.min.css', 'kwec.css'];

async function download(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response;
}

async function loadStylesheet(name, offline) {
  if (offline) {
    return readFile(new URL(name, root), 'utf8');
  }

  const response = await download(`${origin}/css/${name}`);
  return response.text();
}

function findWebfont(fontFace, stylesheetUrl, stylesheetName) {
  const urls = [...fontFace.matchAll(/url\(['"]?([^)'"\s]+)['"]?\)/g)];
  const preferred = urls.find(match => /\.woff2(?:[?#]|$)/.test(match[1]))
    ?? urls.find(match => /\.woff(?:[?#]|$)/.test(match[1]));

  if (!preferred) throw new Error(`Webfont fehlt in ${stylesheetName}`);

  const remote = new URL(preferred[1], stylesheetUrl);
  const filename = remote.pathname.split('/').pop();
  const format = filename.endsWith('.woff2') ? 'woff2' : 'woff';
  return { filename, format, url: remote.href };
}

function localizeFontFace(fontFace, font) {
  // Keep the original family, style and weight; replace only the font sources.
  const descriptors = fontFace.replace(/src\s*:[^;}]*(?:;|(?=\}))/g, '');
  const localSource = `;src:url('/brand/original/fonts/${font.filename}') format('${font.format}');}`;
  return descriptors.replace(/\}$/, localSource);
}

function prepareStylesheet(css, name, fonts) {
  const stylesheetUrl = `${origin}/css/${name}`;
  const fontFaces = [];
  const rules = css.replace(/@font-face\s*\{[^}]*\}/g, fontFace => {
    const font = findWebfont(fontFace, stylesheetUrl, name);
    fonts.set(font.filename, font.url);
    fontFaces.push(localizeFontFace(fontFace, font));
    return '';
  });

  return `${fontFaces.join('\n')}\n${rules}`;
}

async function saveRemoteFile(url, destination) {
  const response = await download(url);
  const bytes = await response.arrayBuffer();
  await writeFile(destination, Buffer.from(bytes));
}

async function syncFonts(fonts) {
  for (const [filename, url] of fonts) {
    await saveRemoteFile(url, new URL(`fonts/${filename}`, root));
  }
}

async function syncMobileLogo() {
  await saveRemoteFile(
    `${origin}/img/logo-wfs-sachsen.png`,
    new URL('../wfs-mobile.png', root),
  );
}

async function saveCombinedStylesheet(styles) {
  const comment = `/* Generated by scripts/sync-chrome-styles.mjs; source: ${origin} */`;
  await writeFile(new URL('chrome.css', root), `${comment}\n${styles.join('\n')}`);
}

async function main() {
  const offline = process.argv.includes('--offline');
  const fonts = new Map();
  const styles = [];

  await mkdir(new URL('fonts/', root), { recursive: true });

  for (const name of stylesheetNames) {
    const css = await loadStylesheet(name, offline);
    await writeFile(new URL(name, root), css);
    styles.push(prepareStylesheet(css, name, fonts));
  }

  if (!offline) {
    await syncFonts(fonts);
  }

  // Apply the source's typography, Bootstrap grid and reset to the entire site.
  await saveCombinedStylesheet(styles);

  if (!offline) {
    await syncMobileLogo();
  }

  console.log(`Original-Styles und ${fonts.size} lokale Webfonts gespeichert.`);
}

await main();
